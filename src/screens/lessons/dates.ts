// Local day label. formatDay() in src/shared uses the en-GB locale, which writes "Sept" in current Chrome.
// The Figma frames show "Sep", so W4 screens use this fixed label until the lead changes formatDay.

const WEEKDAYS = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'];
const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];

/** "2026-09-13" -> "Sun 13 Sep" */
export function shortDay(date: string): string {
  const d = new Date(`${date}T12:00:00Z`);
  return `${WEEKDAYS[d.getUTCDay()]} ${d.getUTCDate()} ${MONTHS[d.getUTCMonth()]}`;
}
